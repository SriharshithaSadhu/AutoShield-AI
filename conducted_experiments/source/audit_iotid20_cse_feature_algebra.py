"""Expanded algebraic consistency checks for IoTID20↔CSE flow features.

Tests CICFlowMeter-derived identities in the full official IoTID20 CSV and a
deterministic per-chunk CSE sample. These checks can detect some units or
mapping errors, but matching identities do not prove full extraction or
exporter equivalence.
"""
from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / "data" / "provenance" / "IoTID20_official_original.csv"
CACHE = ROOT / "data" / "cse_replay_chunk_cache_v2"
OUT = ROOT / "results" / "iotid20_cse_feature_algebra_audit_20261102.json"
SEED = 20261102
FRACTION_PER_CHUNK = 0.01
REL_TOL = 1e-5
ABS_TOL = 1e-4


def canonical(name: str) -> str:
    return re.sub(r"[^a-z0-9]", "", name.casefold())


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def evaluate(frame: pd.DataFrame) -> dict[str, object]:
    def col(name: str) -> np.ndarray:
        return frame[name].to_numpy(dtype=np.float64)

    fd = col("Flow Duration")
    fpk = col("Tot Fwd Pkts")
    bpk = col("Tot Bwd Pkts")
    fbytes = col("TotLen Fwd Pkts")
    bbytes = col("TotLen Bwd Pkts")
    packets = fpk + bpk
    bytes_total = fbytes + bbytes

    def rate_count(rate: np.ndarray) -> np.ndarray:
        valid = np.isfinite(rate) & np.isfinite(fd)
        product = np.zeros_like(fd)
        np.multiply(rate, fd, out=product, where=valid)
        return product / 1e6

    # Exact algebraic relationships supported by CICFlowMeter's published
    # BasicFlow implementation. Packet-length aggregates and packet-size
    # average are intentionally excluded: BasicFlow's flowLengthStats adds
    # the first packet twice, while the output denominator differs by field.
    tests = [
        ("Flow Pkts/s × duration_us / 1e6 = total_packets", rate_count(col("Flow Pkts/s")), packets, fd > 0),
        ("Fwd Pkts/s × duration_us / 1e6 = forward_packets", rate_count(col("Fwd Pkts/s")), fpk, fd > 0),
        ("Bwd Pkts/s × duration_us / 1e6 = backward_packets", rate_count(col("Bwd Pkts/s")), bpk, fd > 0),
        ("Flow Byts/s × duration_us / 1e6 = total_bytes", rate_count(col("Flow Byts/s")), bytes_total, fd > 0),
        ("Fwd Pkt Len Mean × forward_packets = forward_bytes", col("Fwd Pkt Len Mean") * fpk, fbytes, fpk > 0),
        ("Bwd Pkt Len Mean × backward_packets = backward_bytes", col("Bwd Pkt Len Mean") * bpk, bbytes, bpk > 0),
        ("Fwd Seg Size Avg × forward_packets = forward_bytes", col("Fwd Seg Size Avg") * fpk, fbytes, fpk > 0),
        ("Bwd Seg Size Avg × backward_packets = backward_bytes", col("Bwd Seg Size Avg") * bpk, bbytes, bpk > 0),
        ("Subflow Fwd Pkts = forward_packets", col("Subflow Fwd Pkts"), fpk, np.ones(len(fd), dtype=bool)),
        ("Subflow Bwd Pkts = backward_packets", col("Subflow Bwd Pkts"), bpk, np.ones(len(fd), dtype=bool)),
        ("Subflow Fwd Byts = forward_bytes", col("Subflow Fwd Byts"), fbytes, np.ones(len(fd), dtype=bool)),
        ("Subflow Bwd Byts = backward_bytes", col("Subflow Bwd Byts"), bbytes, np.ones(len(fd), dtype=bool)),
        ("Down/Up Ratio = floor(backward_packets / forward_packets) [version-sensitive]",
         col("Down/Up Ratio"), np.floor(np.divide(bpk, fpk, out=np.zeros_like(bpk), where=fpk > 0)), fpk > 0),
    ]
    results = {}
    for name, observed, expected, domain in tests:
        valid = domain & np.isfinite(observed) & np.isfinite(expected)
        observed, expected = observed[valid], expected[valid]
        error = np.abs(observed - expected)
        tolerance = ABS_TOL + REL_TOL * np.abs(expected)
        scaled = error / np.maximum(1.0, np.abs(expected))
        results[name] = {
            "valid_rows": int(len(expected)),
            "fraction_within_tolerance": float(np.mean(error <= tolerance)) if len(expected) else None,
            "relative_error_quantiles": [float(x) for x in np.quantile(scaled, [0, 0.5, 0.95, 0.99, 1])] if len(scaled) else [],
        }
    # Keep non-identity quantities separate. In the current upstream source,
    # Pkt Size Avg is flowLengthStats.sum / packetCount; flowLengthStats
    # includes the first payload twice. Pkt Len Mean is a SummaryStatistics
    # mean over that accumulator. The datasets may have been generated by a
    # different CICFlowMeter revision, so these are descriptive only.
    diagnostic = {
        "Pkt Size Avg × total_packets minus total_bytes": {
            "meaning": "diagnostic residual; current upstream implementation implies it depends on the duplicated first payload",
            "quantiles": [float(x) for x in np.quantile(col("Pkt Size Avg") * packets - bytes_total, [0, .5, .95, .99, 1])],
        },
        "Pkt Len Mean × total_packets minus total_bytes": {
            "meaning": "diagnostic residual; mean denominator/first-packet accumulator are implementation-version sensitive",
            "quantiles": [float(x) for x in np.quantile(col("Pkt Len Mean") * packets - bytes_total, [0, .5, .95, .99, 1])],
        },
    }
    return {"rows": int(len(frame)), "identities": results, "version_sensitive_diagnostics": diagnostic}


def main() -> None:
    manifest = json.loads((CACHE / "manifest.json").read_text(encoding="utf-8"))
    features = manifest["features"]
    needed = {"Flow Duration", "Tot Fwd Pkts", "Tot Bwd Pkts", "TotLen Fwd Pkts", "TotLen Bwd Pkts",
              "Flow Pkts/s", "Fwd Pkts/s", "Bwd Pkts/s", "Flow Byts/s", "Fwd Pkt Len Mean",
              "Bwd Pkt Len Mean", "Pkt Len Mean", "Pkt Size Avg", "Fwd Seg Size Avg", "Bwd Seg Size Avg",
              "Subflow Fwd Pkts", "Subflow Bwd Pkts", "Subflow Fwd Byts", "Subflow Bwd Byts", "Down/Up Ratio"}
    absent = sorted(needed.difference(features))
    if absent:
        raise ValueError(f"Required semantic-check fields missing: {absent}")

    header = pd.read_csv(SOURCE, nrows=0).columns.tolist()
    source_map: dict[str, list[str]] = {}
    for name in header:
        source_map.setdefault(canonical(name), []).append(name)
    mapping = {name: source_map[canonical(name)][0] for name in needed if len(source_map.get(canonical(name), [])) == 1}
    if len(mapping) != len(needed):
        raise ValueError("At least one requested source field is missing or ambiguous")
    raw = pd.read_csv(SOURCE, usecols=list(mapping.values()), low_memory=False)
    reverse = {source_name: feature for feature, source_name in mapping.items()}
    source = raw.rename(columns=reverse)[sorted(needed)]

    rng = np.random.default_rng(SEED)
    parts = []
    sampled_rows = 0
    for chunk in manifest["chunks"]:
        with np.load(CACHE / chunk["file"], allow_pickle=False) as record:
            n = len(record["y"])
            take = min(n, max(1, int(round(n * FRACTION_PER_CHUNK))))
            indices = np.sort(rng.choice(n, size=take, replace=False))
            array = np.asarray(record["x"][indices], dtype=np.float64)
            columns = manifest["features"]
            frame = pd.DataFrame(array, columns=columns)
            parts.append(frame[sorted(needed)])
            sampled_rows += take
    target = pd.concat(parts, ignore_index=True)

    result = {
        "status": "complete", "date": "2026-11-02",
        "audit": "Expanded algebraic consistency checks for flow feature intersections",
        "tolerance": {"relative": REL_TOL, "absolute": ABS_TOL},
        "source": {"path": str(SOURCE.relative_to(ROOT)), "sha256": sha256(SOURCE), **evaluate(source)},
        "target": {"cache": str(CACHE.relative_to(ROOT)), "manifest_sha256": manifest["manifest_sha256"],
                   "sample_fraction_per_chunk": FRACTION_PER_CHUNK, "sampled_rows": sampled_rows, **evaluate(target)},
        "limits": [
            "The tested equations cover derived relationships, not every model input or CICFlowMeter implementation detail.",
            "CICFlowMeter master source is a reference for interpretation, not proof of the exact exporter revision used for either dataset.",
            "Passing algebraic identities cannot prove identical packet parsing, direction assignment, flow timeouts, flag semantics, or labels.",
            "CSE rows inherit the v2 cache's source hashes, timestamp filtering, and inclusion rules.",
        ],
    }
    OUT.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({
        "output": str(OUT), "source_rows": result["source"]["rows"], "target_rows": sampled_rows,
        "source_pass": {k: v["fraction_within_tolerance"] for k, v in result["source"]["identities"].items()},
        "target_pass": {k: v["fraction_within_tolerance"] for k, v in result["target"]["identities"].items()},
    }, indent=2), flush=True)


if __name__ == "__main__":
    main()
